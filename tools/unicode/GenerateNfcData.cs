// Generates the Unicode tables behind MySync.Domain.Paths.Normalization.NfcNormalizer
// (CLAUDE.md §8) from the Unicode Character Database, and refreshes the conformance test data.
//
//   dotnet run tools/unicode/GenerateNfcData.cs -- 17.0.0      (from the repo root)
//   nx run mysync-domain:generate-unicode
//
// Bump the version only deliberately: a new Unicode version can change which manifest keys two
// machines compute for the same name, so every client must agree on it.

using System.Globalization;
using System.IO.Compression;
using System.Text;

string version = args.Length > 0 ? args[0] : "17.0.0";

if (!File.Exists("mysync.slnx"))
{
    throw new InvalidOperationException("Run from the repository root (where mysync.slnx is).");
}

const string DataFile = "libs/mysync/domain/Paths/Normalization/UnicodeNormalizationData.g.cs";
const string TestFile = "tests/mysync/domain-unit-tests/Paths/Normalization/NormalizationTest.txt.gz";

using HttpClient http = new();
string baseUrl = $"https://www.unicode.org/Public/{version}/ucd/";

string unicodeData = await http.GetStringAsync(new Uri(baseUrl + "UnicodeData.txt"));
string normalizationProps = await http.GetStringAsync(new Uri(baseUrl + "DerivedNormalizationProps.txt"));
byte[] normalizationTest = await http.GetByteArrayAsync(new Uri(baseUrl + "NormalizationTest.txt"));

SortedDictionary<int, int> combiningClasses = [];
SortedDictionary<int, int[]> canonicalMappings = [];

foreach (string line in unicodeData.Split('\n', StringSplitOptions.RemoveEmptyEntries))
{
    string[] fields = line.Split(';');
    int codePoint = ParseHex(fields[0]);
    int combiningClass = int.Parse(fields[3], CultureInfo.InvariantCulture);
    string decomposition = fields[5];

    if (combiningClass != 0)
    {
        combiningClasses[codePoint] = combiningClass;
    }

    // "<tag> ..." mappings are compatibility decompositions; NFC uses canonical ones only.
    if (decomposition.Length > 0 && decomposition[0] != '<')
    {
        canonicalMappings[codePoint] = [.. decomposition.Split(' ').Select(ParseHex)];
    }
}

HashSet<int> compositionExclusions = [];

foreach (string line in normalizationProps.Split('\n'))
{
    string content = line.Split('#')[0];
    string[] parts = content.Split(';', StringSplitOptions.TrimEntries);

    if (parts.Length < 2 || parts[1] != "Full_Composition_Exclusion")
    {
        continue;
    }

    string[] range = parts[0].Split("..");
    int first = ParseHex(range[0]);
    int last = range.Length > 1 ? ParseHex(range[1]) : first;

    for (int codePoint = first; codePoint <= last; codePoint++)
    {
        compositionExclusions.Add(codePoint);
    }
}

StringBuilder source = new();
source.Append("// <auto-generated/>\r\n");
source.Append(CultureInfo.InvariantCulture, $"// Generated by tools/unicode/GenerateNfcData.cs from the Unicode Character Database {version}.\r\n");
source.Append("// Do not edit by hand; re-run the generator (CLAUDE.md §8).\r\n\r\n");
source.Append("namespace MySync.Domain.Paths.Normalization;\r\n\r\n");
source.Append("internal static class UnicodeNormalizationData\r\n{\r\n");
source.Append(CultureInfo.InvariantCulture, $"    internal const string UnicodeVersion = \"{version}\";\r\n\r\n");

// Ranges of consecutive code points sharing one non-zero combining class: start, end, class.
List<int> classRanges = [];
foreach ((int codePoint, int combiningClass) in combiningClasses)
{
    if (classRanges.Count > 0 && classRanges[^2] == codePoint - 1 && classRanges[^1] == combiningClass)
    {
        classRanges[^2] = codePoint;
    }
    else
    {
        classRanges.AddRange([codePoint, codePoint, combiningClass]);
    }
}

AppendTable(source, "Canonical combining classes, sorted: start, end, class (all others are 0).", "CombiningClassRanges", classRanges);

// Full (recursive) canonical decompositions, sorted: code point, length, mapping.... Hangul
// syllables are decomposed algorithmically and are not listed.
List<int> decompositions = [];
foreach (int codePoint in canonicalMappings.Keys)
{
    List<int> full = [];
    Decompose(codePoint, full);
    decompositions.Add(codePoint);
    decompositions.Add(full.Count);
    decompositions.AddRange(full);
}

AppendTable(source, "Full canonical decompositions, sorted: code point, length, mapping...", "Decompositions", decompositions);

// Primary composites: pairs whose canonical mapping is two code points and which are not
// Full_Composition_Exclusion. first, second, composite.
List<int> compositions = [];
foreach ((int codePoint, int[] mapping) in canonicalMappings)
{
    if (mapping.Length == 2 && !compositionExclusions.Contains(codePoint))
    {
        compositions.AddRange([mapping[0], mapping[1], codePoint]);
    }
}

AppendTable(source, "Primary composites: first, second, composite.", "Compositions", compositions);
source.Append("}\r\n");

await File.WriteAllTextAsync(DataFile, source.ToString(), new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));

await using (FileStream output = File.Create(TestFile))
await using (GZipStream gzip = new(output, CompressionLevel.SmallestSize))
{
    await gzip.WriteAsync(normalizationTest);
}

await Console.Out.WriteLineAsync(
    string.Create(CultureInfo.InvariantCulture, $"Unicode {version}: {classRanges.Count / 3} class ranges, {canonicalMappings.Count} decompositions, {compositions.Count / 3} compositions."));

void Decompose(int codePoint, List<int> target)
{
    if (canonicalMappings.TryGetValue(codePoint, out int[]? mapping))
    {
        foreach (int part in mapping)
        {
            Decompose(part, target);
        }
    }
    else
    {
        target.Add(codePoint);
    }
}

static int ParseHex(string value) => int.Parse(value, NumberStyles.HexNumber, CultureInfo.InvariantCulture);

static void AppendTable(StringBuilder source, string comment, string name, List<int> values)
{
    source.Append(CultureInfo.InvariantCulture, $"    // {comment}\r\n");
    source.Append(CultureInfo.InvariantCulture, $"    internal static ReadOnlySpan<int> {name} =>\r\n    [");

    for (int i = 0; i < values.Count; i++)
    {
        source.Append(i % 12 == 0 ? "\r\n        " : " ");
        source.Append(CultureInfo.InvariantCulture, $"0x{values[i]:X},");
    }

    source.Append("\r\n    ];\r\n\r\n");
}
